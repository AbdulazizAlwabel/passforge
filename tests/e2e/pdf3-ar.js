const { chromium } = require('playwright-core'); const fs = require('fs'); const { execSync } = require('child_process');
const F = process.env.F, DL = process.env.DL, OUT = process.env.OUT, B = process.env.B || 'http://localhost:8899';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const br = await chromium.launch({ executablePath: require('../chrome') });
  const ctx = await br.newContext({ viewport: { width: 1340, height: 900 }, colorScheme: 'dark', acceptDownloads: true });
  const p = await ctx.newPage(); const errs = [], bad = []; p.on('pageerror', e => errs.push(e.message));
  p.on('response', r => { if (r.status() >= 400 && !/\/api\/me/.test(r.url())) bad.push(r.status() + ' ' + r.url()); });
  await p.goto(B + '/ar/pdf-studio/'); await p.setInputFiles('#fileIn', [F + '/photos-a4.pdf', F + '/personal.pdf']);
  await p.waitForFunction(() => window.__studio.pages.length === 3);
  await p.click('#saveOpts'); await p.click('#dlgDl [data-cmp=balanced]'); await p.waitForTimeout(300);
  await p.screenshot({ path: OUT + '/ar-dlopts.png' });
  const [d] = await Promise.all([p.waitForEvent('download', { timeout: 120000 }), p.click('#dlgDl [value=save]')]); const f = DL + '/ar-cmp.pdf'; await d.saveAs(f);
  ok(fs.statSync(f).size < 1500000, 'Arabic UI: compression works (' + (fs.statSync(f).size / 1048576).toFixed(2) + ' MB)');
  await p.waitForTimeout(400); ok(/كان/.test(await p.evaluate(() => document.querySelector('.toast')?.textContent || '')), 'Arabic size toast');
  await p.click('#saveOpts'); await p.click('#dlgDl [data-cmp=off]'); await p.click('#dlgDl [value=ok]');
  await p.click('#moreBtn'); await p.click('[data-act=find]'); await p.click('#findRun'); await p.waitForSelector('#findGo:not([hidden])', { timeout: 30000 });
  ok(/رقم الهوية/.test(await p.innerText('#findRes')) && /الآيبان/.test(await p.innerText('#findRes')), 'Arabic result labels');
  await p.screenshot({ path: OUT + '/ar-find.png' });
  await p.click('#findGo'); await p.waitForTimeout(500);
  await p.dblclick('#grid > .pg:nth-child(3) .pg-paper'); await p.waitForSelector('#viewSpin', { state: 'hidden' }); await p.waitForTimeout(400);
  await p.screenshot({ path: OUT + '/ar-redact-editor.png' }); await p.click('#vClose');
  await p.setInputFiles('#fileIn', [F + '/scanned.pdf']); await p.waitForFunction(() => window.__studio.pages.length === 4);
  await p.click('#grid > .pg:nth-child(4) .pg-paper');
  await p.click('#moreBtn'); await p.click('[data-act=ocr]'); await p.click('#dlgOcr [data-ow=sel]'); await p.click('#ocrStart');
  await p.waitForSelector('#ocrActs:not([hidden])', { timeout: 240000 });
  const ot = await p.inputValue('#ocrOut'); ok(/فاتورة ضريبية/.test(ot) && /عبدالعزيز الوابل/.test(ot), 'Arabic UI: OCR result keeps word spaces');
  await p.screenshot({ path: OUT + '/ar-ocr.png' });
  ok(!bad.length, 'no failed requests ' + bad.join(' | '));
  ok(!errs.length, 'no errors ' + errs.join(' | '));
  await br.close(); console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
})().catch(e => { console.error(e); process.exit(2); });
