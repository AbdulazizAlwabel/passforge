// Records the still frame of the home page's glass (src/assets/prism-still.webp).
// The picture is not drawn by hand or generated: it is one frame of the same shader the page runs
// (src/assets/prism.js), at its resting pose, saved from the canvas. It is what the page loads with,
// and what stays when motion is reduced, WebGL is missing, or the device is low on memory or data.
//
//   bash tests/run.sh e2e        (or anything else that leaves the test server on :8899)
//   node tools/prism-still.js    → src/assets/prism-still.webp, and docs/provenance/prism-still.webp.json (where it came from)
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const T = path.resolve(__dirname, '../tests');
const { chromium } = require(T + '/node_modules/playwright-core');
const B = process.env.B || 'http://localhost:8899';
const W = 1300, H = 1000, OUT = path.resolve(__dirname, '../src/assets/prism-still.webp');
(async () => {
  const br = await chromium.launch({ executablePath: require(T + '/chrome.js'), args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const p = await (await br.newContext({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' })).newPage();
  await p.addInitScript(() => { window.ND_PRISM_KEEP = true; });   // software WebGL is slow; keep the canvas so its frame can be saved
  await p.goto(B + '/'); await p.waitForSelector('.slab.live', { timeout: 30000 });
  const url = await p.evaluate(([w, h]) => window.NDPrism.still(w, h, 'image/webp', 0.94), [W, H]);
  await br.close();
  if (!url || !url.startsWith('data:image/webp')) throw new Error('the canvas did not give a WebP frame');
  const buf = Buffer.from(url.split(',')[1], 'base64');
  fs.writeFileSync(OUT, buf);
  const src = fs.readFileSync(path.resolve(__dirname, '../src/assets/prism.js'));
  fs.writeFileSync(path.resolve(__dirname, '../docs/provenance/prism-still.webp.json'), JSON.stringify({
    file: 'src/assets/prism-still.webp', width: W, height: H,
    origin: 'A captured frame of the site\'s own WebGL fragment shader (src/assets/prism.js), saved with canvas.toDataURL. Not generated by an image model, not stock.',
    how: 'node tools/prism-still.js', pose: { yaw: 0.55, pitch: -0.18, time: 2.4 },
    shader_sha256: crypto.createHash('sha256').update(src).digest('hex'), captured: new Date().toISOString().slice(0, 10),
  }, null, 2) + '\n');
  console.log('saved', OUT, buf.length, 'bytes');
})().catch((e) => { console.error(e); process.exit(1); });
